type UnknownRecord = Record<string, unknown>;

function isRecord(value: unknown): value is UnknownRecord {
    return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isNonEmptyString(value: unknown): value is string {
    return typeof value === "string" && value.trim().length > 0;
}

function isCommitProvenance(value: unknown): value is string {
    return (
        value === CAPTURE_COMMIT_PROVENANCE_PLACEHOLDER ||
        (typeof value === "string" && /^[0-9a-f]{40}$/.test(value))
    );
}

/**
 * Pure validation used by the focused contract test and by any future capture integration.
 */
export function validateCaptureMatrix(input: readonly unknown[]): string[] {
    const issues: string[] = [];
    const seenNames = new Set<string>();
    const categories = new Set<string>(CAPTURE_CATEGORIES);
    const themes = new Set<string>(["light", "dark", "high-contrast"]);
    const classifications = new Set<string>(["required", "soft-skip"]);

    input.forEach((candidate, index) => {
        if (!isRecord(candidate)) {
            issues.push(`entry[${index}] must be an object`);
            return;
        }

        for (const field of CAPTURE_MATRIX_FIELDS) {
            if (!(field in candidate)) {
                issues.push(`entry[${index}] is missing required field '${field}'`);
            }
        }

        const name = candidate.name;
        if (!isNonEmptyString(name)) {
            issues.push(`entry[${index}] field 'name' must be a non-empty string`);
        } else {
            if (!/^[a-z0-9]+(?:[a-z0-9_-]*[a-z0-9])?$/.test(name)) {
                issues.push(`entry[${index}] field 'name' is not a stable capture name`);
            }
            if (seenNames.has(name)) issues.push(`duplicate capture name '${name}'`);
            seenNames.add(name);
        }

        if (candidate.classification === "required") {
            if (!isNonEmptyString(candidate.file)) {
                issues.push(`entry[${index}] required capture must name its PNG file`);
            } else if (isNonEmptyString(name) && candidate.file !== `${name}.png`) {
                issues.push(`entry[${index}] file must be exactly '${name}.png'`);
            }
        }
        if (candidate.classification === "soft-skip" && candidate.file !== null) {
            issues.push(`entry[${index}] soft-skip capture must use a null file`);
        }

        if (!isNonEmptyString(candidate.alt) || candidate.alt.trim().length < 24) {
            issues.push(
                `entry[${index}] field 'alt' must be useful text of at least 24 characters`,
            );
        }
        if (!isNonEmptyString(candidate.category) || !categories.has(candidate.category)) {
            issues.push(`entry[${index}] field 'category' is not a declared capture category`);
        }
        if (!isNonEmptyString(candidate.theme) || !themes.has(candidate.theme)) {
            issues.push(`entry[${index}] field 'theme' must be light, dark, or high-contrast`);
        }
        if (!isNonEmptyString(candidate.viewport) || !/^\d+x\d+@\d+%$/.test(candidate.viewport)) {
            issues.push(`entry[${index}] field 'viewport' must use WIDTHxHEIGHT@SCALE%`);
        }
        if (!isNonEmptyString(candidate.state)) {
            issues.push(`entry[${index}] field 'state' must be a non-empty string`);
        }
        if (!isNonEmptyString(candidate.expectedSurface)) {
            issues.push(`entry[${index}] field 'expectedSurface' must be a non-empty string`);
        }
        if (
            !isNonEmptyString(candidate.classification) ||
            !classifications.has(candidate.classification)
        ) {
            issues.push(`entry[${index}] field 'classification' must be required or soft-skip`);
        }
        if (candidate.classification === "required" && candidate.softSkipReason !== null) {
            issues.push(`entry[${index}] required capture must use a null softSkipReason`);
        }
        if (
            candidate.classification === "soft-skip" &&
            !isNonEmptyString(candidate.softSkipReason)
        ) {
            issues.push(`entry[${index}] soft-skip capture must name its external precondition`);
        }
        if (!isCommitProvenance(candidate.commitProvenance)) {
            issues.push(
                `entry[${index}] commitProvenance must be the placeholder or a full lowercase commit`,
            );
        }
    });

    for (const name of EXPECTED_CAPTURE_NAMES) {
        if (!seenNames.has(name)) issues.push(`missing required capture '${name}'`);
    }
    const expectedNames = new Set<string>(EXPECTED_CAPTURE_NAMES);
    for (const name of seenNames) {
        if (!expectedNames.has(name)) issues.push(`unexpected capture '${name}'`);
    }

    return issues;
}
