/**
 * Hand-written contract for the application capture matrix.
 *
 * This is intentionally independent of the capture steps and the published gallery. Deriving the
 * inventory from either consumer would let deleting a capture delete its requirement at the same
 * time. Each planned state remains here even when an external account, service, or piece of
 * hardware prevents the image from being produced; those states are explicit soft skips rather
 * than disappearing from the evidence set.
 */

export const CAPTURE_COMMIT_PROVENANCE_PLACEHOLDER = "<exact-candidate-commit>" as const;

/**
 * Publication replaces the placeholder in emitted metadata with the full lowercase 40-character
 * commit that built and launched the captured application. A branch, tag, short SHA, dirty tree,
 * or commit from a different checkout does not satisfy this contract.
 */
export const CAPTURE_COMMIT_PROVENANCE_CONTRACT =
    "Replace <exact-candidate-commit> with the full lowercase 40-character commit that built and launched the captured application.";

