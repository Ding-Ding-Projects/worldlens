export type CaptureCategory = (typeof CAPTURE_CATEGORIES)[number];
export type CaptureTheme = "light" | "dark" | "high-contrast";
export type CaptureClassification = "required" | "soft-skip";

export interface CaptureMatrixEntry {
    readonly name: string;
    /** Required captures name their PNG. A soft skip has no file and therefore uses null. */
    readonly file: string | null;
    readonly alt: string;
    readonly category: CaptureCategory;
    readonly theme: CaptureTheme;
    /** CSS viewport followed by the display scale, for example `1280x800@100%`. */
    readonly viewport: string;
    readonly state: string;
    readonly expectedSurface: string;
    readonly classification: CaptureClassification;
    /** Required captures use null. Soft skips name the exact missing external precondition. */
    readonly softSkipReason: string | null;
    /** The placeholder above while planning, or the exact resolved commit in emitted metadata. */
    readonly commitProvenance: string;
}

