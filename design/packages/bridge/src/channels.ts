/**
 * Every channel the bridge can reach, written out by hand.
 *
 * ## Why a hand-written list rather than a scan
 *
 * A guard that discovers its own subjects can only ever check the things it found. It
 * cannot notice the thing that is missing, and it cannot notice a thing that was added
 * without anybody deciding it should exist. Both matter here, for different reasons.
 *
 * A channel added to the factory and not to this list is a channel that has become
 * reachable without a hosting decision being taken about it. In a desktop build that is
 * harmless, because everything is already local. In a hosted deployment it is a new hole in
 * a surface exposed over a network, arriving by default. `channels.test.ts` asserts this
 * list and the factory agree exactly, in both directions, so neither can move alone.
 *
 * ## What this list is not
 *
 * It is not the set of channels the main process registers - that is larger, and includes
 * channels no renderer ever calls. This is specifically the reachable surface: what a
 * renderer, and therefore a browser tab in a hosted deployment, can actually ask for.
 */

